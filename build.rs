use std::env;
use std::fs;
use std::path::Path;

fn main() {
    // 1. Re-run if config changes
    println!("cargo:rerun-if-changed=config/constants.toml");

    // 2. Read TOML
    let config_path = Path::new("config/constants.toml");
    let content = fs::read_to_string(config_path).expect("Failed to read config/constants.toml");

    // 3. Extract all constants
    let protocol_version = extract_u64(&content, "protocol_version");
    let socket_limit = extract_u64(&content, "socket_path_limit");
    let max_message_size = extract_u64(&content, "max_message_size");
    let slow_threshold_ms = extract_u64(&content, "default_slow_threshold_ms");
    let pyproject_toml = extract_str(&content, "pyproject_toml");
    let uv_lock = extract_str(&content, "uv_lock");
    let requirements_txt = extract_str(&content, "requirements_txt");
    let site_customize = extract_str(&content, "site_customize");
    let velo_loader = extract_str(&content, "velo_loader");
    let velo_cache_dir = extract_str(&content, "velo_cache_dir");
    let velo_profile_json = extract_str(&content, "velo_profile_json");
    let socket_startup_timeout = extract_u64(&content, "socket_startup_timeout");
    let worker_handshake_timeout = extract_u64(&content, "worker_handshake_timeout");
    let graceful_shutdown_timeout = extract_u64(&content, "graceful_shutdown_timeout");
    let default_host = extract_str(&content, "default_host");
    let default_port = extract_u64(&content, "default_port");

    // 4. Generate Rust Constants
    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("constants.rs");

    let rust_code = format!(
        "// Auto-generated by build.rs. DO NOT EDIT.\n\
         pub const PROTOCOL_VERSION: u8 = {};\n\
         pub const SOCKET_PATH_LIMIT: usize = {};\n\
         pub const MAX_MESSAGE_SIZE: usize = {};\n\
         pub const DEFAULT_SLOW_THRESHOLD_MS: u64 = {};\n\
         pub const PYPROJECT_TOML: &str = \"{}\";\n\
         pub const UV_LOCK: &str = \"{}\";\n\
         pub const REQUIREMENTS_TXT: &str = \"{}\";\n\
         pub const SITE_CUSTOMIZE: &str = \"{}\";\n\
         pub const VELO_LOADER: &str = \"{}\";\n\
         pub const VELO_CACHE_DIR: &str = \"{}\";\n\
         pub const VELO_PROFILE_JSON: &str = \"{}\";\n\
         pub const SOCKET_STARTUP_TIMEOUT: u64 = {};\n\
         pub const WORKER_HANDSHAKE_TIMEOUT: u64 = {};\n\
         pub const GRACEFUL_SHUTDOWN_TIMEOUT: u64 = {};\n\
         pub const DEFAULT_HOST: &str = \"{}\";\n\
         pub const DEFAULT_PORT: u16 = {};\n",
        protocol_version,
        socket_limit,
        max_message_size,
        slow_threshold_ms,
        pyproject_toml,
        uv_lock,
        requirements_txt,
        site_customize,
        velo_loader,
        velo_cache_dir,
        velo_profile_json,
        socket_startup_timeout,
        worker_handshake_timeout,
        graceful_shutdown_timeout,
        default_host,
        default_port
    );
    fs::write(&dest_path, rust_code).unwrap();

    // 5. Generate Python Constants
    let py_path = Path::new("velo_zygote/constants.py");
    let python_constants = format!(
        "# Auto-generated by build.rs. DO NOT EDIT.\n\
         PROTOCOL_VERSION = {}\n\
         SOCKET_PATH_LIMIT = {}\n\
         MAX_MESSAGE_SIZE = {}\n\
         DEFAULT_SLOW_THRESHOLD_MS = {}\n\
         PYPROJECT_TOML = \"{}\"\n\
         UV_LOCK = \"{}\"\n\
         REQUIREMENTS_TXT = \"{}\"\n\
         SITE_CUSTOMIZE = \"{}\"\n\
         VELO_LOADER = \"{}\"\n\
         VELO_CACHE_DIR = \"{}\"\n\
         VELO_PROFILE_JSON = \"{}\"\n\
         SOCKET_STARTUP_TIMEOUT = {}\n\
         WORKER_HANDSHAKE_TIMEOUT = {}\n\
         GRACEFUL_SHUTDOWN_TIMEOUT = {}\n\
         DEFAULT_HOST = \"{}\"\n\
         DEFAULT_PORT = {}\n",
        protocol_version,
        socket_limit,
        max_message_size,
        slow_threshold_ms,
        pyproject_toml,
        uv_lock,
        requirements_txt,
        site_customize,
        velo_loader,
        velo_cache_dir,
        velo_profile_json,
        socket_startup_timeout,
        worker_handshake_timeout,
        graceful_shutdown_timeout,
        default_host,
        default_port
    );
    fs::write(py_path, python_constants).unwrap();
}

fn extract_u64(toml: &str, key: &str) -> u64 {
    for line in toml.lines() {
        let line = line.trim();
        if !line.starts_with(key) {
            continue;
        }

        if let Some(val_str) = line.split('=').nth(1) {
            return val_str
                .trim()
                .parse()
                .unwrap_or_else(|_| panic!("Invalid number for key {}", key));
        }
    }
    panic!("Key {} not found", key);
}

fn extract_str(toml: &str, key: &str) -> String {
    for line in toml.lines() {
        let line = line.trim();
        if !line.starts_with(key) {
            continue;
        }

        if let Some(val_str) = line.split('=').nth(1) {
            return val_str.trim().trim_matches('"').to_string();
        }
    }
    panic!("Key {} not found", key);
}
